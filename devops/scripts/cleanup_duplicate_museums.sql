-- cleanup_duplicate_museums.sql
-- ---------------------------------------------------------------------------
-- 删除上一轮同步在 production `museums` 表误建的 12 行"无统计副本"。
-- 这些行是精确名（如 `苏州博物馆`）但 visitor_count IS NULL，shadow 了真正
-- 带统计的注册表行（`苏州博物馆（苏州民俗博物馆、苏州工艺美术博物馆）`），
-- 导致付费产品 resolveTreasureMuseum 拿到 2 个候选 → 解析失败。
--
-- 真行已在本次同步中补好馆照且统计完好，删除副本不丢任何有效数据。
-- 用 `AND visitor_count IS NULL` 兜底：万一误列了带统计行也绝不会删。
-- 先在 Lighthouse 上用只读 SELECT 复核，再执行 DELETE。
-- ---------------------------------------------------------------------------

-- 0) 复核：应返回 12 行，且全部 visitor_count IS NULL
SELECT dedupe_key, name, province, visitor_count, image_url
FROM museums
WHERE dedupe_key IN (
  '陕西省_秦始皇帝陵博物院',
  '江苏省_苏州博物馆',
  '浙江省_浙江省博物馆',
  '广东省_广东省博物馆',
  '山东省_山东博物馆',
  '重庆市_重庆中国三峡博物馆',
  '浙江省_杭州博物馆',
  '安徽省_安徽博物院',
  '浙江省_嘉兴博物馆',
  '吉林省_吉林省博物院',
  '天津市_天津自然博物馆',
  '北京市_中国考古博物馆'
)
AND visitor_count IS NULL;

-- 1) 执行删除（仅删上述无统计副本）
