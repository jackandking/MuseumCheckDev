#!/usr/bin/env node

/**
 * Generate js/museums-meta.js from data/museums-meta.json
 * 
 * This tool creates the JavaScript file that the homepage loads
 * to display the museum list. It reads from the authoritative
 * JSON file and generates a JS file with window.MUSEUMS_META.
 * 
 * Usage: node tools/generate-museums-meta-js.js
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
const jsonFile = path.join(root, 'data', 'museums-meta.json');
const outFile = path.join(root, 'js', 'museums-meta.js');

function main() {
  console.log('📦 Generating js/museums-meta.js from museums-meta.json...\n');
  
  // Read the JSON file
  if (!fs.existsSync(jsonFile)) {
    console.error(`❌ Error: ${jsonFile} not found`);
    process.exit(1);
  }
  
  const content = fs.readFileSync(jsonFile, 'utf8');
  let meta;
  
  try {
    meta = JSON.parse(content);
  } catch (error) {
    console.error(`❌ Error parsing JSON: ${error.message}`);
    process.exit(1);
  }
  
  if (!Array.isArray(meta)) {
    console.error('❌ Error: museums-meta.json must contain an array');
    process.exit(1);
  }
  
  // Generate the JavaScript file content
  const jsContent = `/**
 * Museums Meta Data - Lightweight listing for homepage
 * Auto-generated from data/museums-meta.json
 * 
 * DO NOT EDIT THIS FILE MANUALLY
 * To update: modify data/museums-meta.json and run:
 *   node tools/generate-museums-meta-js.js
 * 
 * This file provides lightweight metadata for homepage display.
 * Full museum details (collections, checklists) are loaded dynamically from KV Store.
 */

window.MUSEUMS_META = ${JSON.stringify(meta, null, 2)};

// Helper to update cache when this script loads
window.__updateMuseumsMetaCache = function(data) {
  if (window.dataManager) {
    console.log('[museums-meta.js] Loaded ' + data.length + ' museums from meta');
  }
};
`;
  
  // Ensure output directory exists
  const outDir = path.dirname(outFile);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }
  
  // Write the JavaScript file
  fs.writeFileSync(outFile, jsContent, 'utf8');
  
  console.log(`✅ Generated ${outFile}`);
  console.log(`   Museums: ${meta.length}`);
  console.log(`   Size: ${(jsContent.length / 1024).toFixed(2)} KB\n`);
  
  // Verify the generated file
  const beijing = meta.find(m => m.id === 'beijing-natural-history-museum');
  if (beijing) {
    console.log(`✅ Verification: beijing-natural-history-museum found`);
    console.log(`   Name: ${beijing.name}`);
    console.log(`   hasCollections: ${beijing.hasCollections}`);
  } else {
    console.warn(`⚠️  Warning: beijing-natural-history-museum not found in meta`);
  }
}

if (require.main === module) {
  main();
}

module.exports = { main };
